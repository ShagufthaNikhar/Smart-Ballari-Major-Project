(async () => {
  await mongoose.connect(process.env.MONGO_URI);
  console.log('Connected to MongoDB');

  if (process.argv.includes('--reset')) {
    const { deletedCount } = await VerifiedJob.deleteMany({});
    console.log(`Reset: removed ${deletedCount} jobs`);
  }

  let created = 0, updated = 0;

  for (const doc of SEED_DATA) {
    const res = await VerifiedJob.updateOne(
      { slug: doc.slug },
      { $set: doc },
      { upsert: true }
    );
    if (res.upsertedCount) created++; else if (res.modifiedCount) updated++;
  }

  const total = await VerifiedJob.countDocuments();
  console.log(`\ncreated ${created}, updated ${updated}, total in DB ${total}`);

  const byCat = await VerifiedJob.aggregate([
    { $group: { _id: '$category', n: { $sum: 1 } } }, { $sort: { n: -1 } }
  ]);
  console.log('\nby category:');
  byCat.forEach(r => console.log(`  ${String(r.n).padStart(4)}  ${r._id}`));

  await mongoose.disconnect();
})().catch(err => { console.error(err); process.exit(1); });